def print_thread_info(core, thread, elf=None):
    """Print summary information about a thread."""
    name = thread.name
    if thread.stop_reason != 0:
        name = red(bold(name))
    else:
        name = cyan(name)

    iprint(name)
    with indent():
        iprint(f"ID: 0x{thread.uid:x}")

        reason_str = STR_STOP_REASON[thread.stop_reason]
        if thread.stop_reason != 0:
            iprint(red(f"Stop reason: 0x{thread.stop_reason:x} ({reason_str})"))
        else:
            iprint(f"Stop reason: 0x{thread.stop_reason:x} ({reason_str})")

        iprint(f"Status: 0x{thread.status:x} ({STR_STATUS[thread.status]})")

        pc = core.get_address_notation("PC", thread.pc)
        iprint(pc.to_string(elf))
        if not pc.is_located() and thread.regs:
            lr = core.get_address_notation("LR", thread.regs.gpr[14])
            iprint(lr.to_string(elf))


# Matches compiler-generated data labels: .LC0, .LANCHOR1, etc.
# Deliberately avoids matching .Lfunc_begin / .Ltext0 which are valid code labels.
_DATA_LABEL_RE = re.compile(r"\.(LC|LANCHOR)\d+")


def _is_likely_return_addr(offset, elf):
    """Heuristic check: is this address likely a return address (i.e. instruction
    after a BL/BLX call) rather than a data pointer or function pointer?

    We check the addr2line result to filter out obvious non-code entries like
    data labels (.LC*) and anchors (.LANCHOR*).
    """
    if not elf:
        return True  # Can't filter without addr2line, assume it's valid

    a2l_result = elf.addr2line(offset)
    if not a2l_result:
        return True  # No info, keep it

    # Filter out compiler-generated data labels (.LC0, .LANCHOR1, etc.)
    if _DATA_LABEL_RE.search(a2l_result):
        return False

    return True


def reconstruct_callstack(core, thread, elf, max_depth=32):
    """Reconstruct call stack using heuristic stack scanning.

    Strategy:
    1. Start with PC (current crash location)
    2. Add LR (direct caller return address)
    3. Scan the stack for values that point into executable (RX) segments
       These are candidate return addresses from the call chain.

    This is a heuristic approach - it may include false positives (e.g. function
    pointers stored on the stack) but provides a useful approximation when
    frame pointers are not available (common with -fomit-frame-pointer).
    """
    if not thread.regs:
        return []

    callstack = []
    seen_addrs = set()

    # Frame #0: PC (crash location)
    pc_val = thread.pc
    pc_notation = core.get_address_notation("PC", pc_val)
    callstack.append(("PC", pc_val, pc_notation, None, True))
    seen_addrs.add(pc_val & ~1)

    # Frame #1: LR (direct caller)
    lr_val = thread.regs.gpr[14]
    if lr_val != 0 and (lr_val & ~1) not in seen_addrs:
        lr_info = core.is_code_address(lr_val)
        if lr_info:
            lr_notation = core.get_address_notation("LR", lr_val)
            callstack.append(("LR", lr_val, lr_notation, None, True))
            seen_addrs.add(lr_val & ~1)

    # Scan stack for return addresses
    sp = thread.regs.gpr[13]
    # Scan a generous range of the stack (up to 512 words = 2KB)
    scan_words = 512
    for i in range(scan_words):
        if len(callstack) >= max_depth:
            break

        addr = sp + i * 4
        data = core.read_vaddr(addr, 4)
        if not data or len(data) < 4:
            continue

        val = u32(data, 0)
        if val == 0:
            continue

        # Skip if we've already seen this address
        val_clean = val & ~1
        if val_clean in seen_addrs:
            continue

        # Check if this value points to executable code
        code_info = core.is_code_address(val)
        if code_info:
            module, segment, offset = code_info
            # Filter: skip addresses that resolve to data labels (not real code)
            if not _is_likely_return_addr(offset, elf):
                continue

            notation = core.get_address_notation(f"[SP+0x{i*4:x}]", val)
            callstack.append((f"[SP+0x{i*4:x}]", val, notation, addr, False))
            seen_addrs.add(val_clean)

    return callstack


def print_callstack(core, thread, elf, max_depth=32):
    """Print reconstructed call stack for a crashed thread."""
    callstack = reconstruct_callstack(core, thread, elf, max_depth)

    if not callstack:
        iprint(yellow("  (unable to reconstruct call stack)"))
        return

    iprint(bold("CALL STACK (heuristic reconstruction):"))
    iprint(dim("  Note: Frames from stack scanning may include false positives (marked with '?')."))
    iprint(dim("  PC and LR frames are reliable. [SP+offset] frames are heuristic candidates."))
    iprint()

    with indent():
        for idx, (source, vaddr, notation, stack_addr, reliable) in enumerate(callstack):
            # Resolve symbol via addr2line if possible
            sym_str = ""
            if elf and notation.is_located() and notation._offset is not None:
                a2l_result = elf.addr2line(notation._offset)
                if a2l_result:
                    sym_str = f" => {a2l_result}"

            addr_display = vaddr & ~1
            if notation.is_located():
                loc = f"{notation._module.name}@{notation._segment.num} + 0x{notation._offset:x}"
            else:
                loc = "??"

            confidence = " " if reliable else "?"
            frame_str = f"#{idx:<3} {confidence} 0x{addr_display:08x}  {loc}{sym_str}"
            if reliable:
                prefix = f"  {source:>12}"
                iprint(f"{cyan(prefix)}  {frame_str}")
            else:
                prefix = f"  {source:>12}"
                iprint(f"{dim(prefix)}  {frame_str}")


def analyze_crash(core, thread, elf, stack_size):
    """Perform detailed analysis of a crashed thread."""
    reason_str = STR_STOP_REASON[thread.stop_reason]
    iprint(red(bold(f'=== THREAD "{thread.name}" <0x{thread.uid:x}> CRASHED ({reason_str}) ===')))

    if not thread.regs:
        iprint(yellow("  (no register data available for this thread)"))
        return

    # Disassembly around PC and LR
    pc = core.get_address_notation("PC", thread.pc)
    pc.print_disas_if_available(elf)

    lr = core.get_address_notation("LR", thread.regs.gpr[14])
    lr.print_disas_if_available(elf)

    # Reconstructed call stack
    iprint()
    print_callstack(core, thread, elf)

    # Register dump
    iprint()
    iprint(bold("REGISTERS:"))
    with indent():
        for x in range(13):
            reg = f"R{x}"
            iprint(f"{reg:>4}: 0x{thread.regs.gpr[x]:08x}")
        iprint(f"  SP: 0x{thread.regs.gpr[13]:08x}")
        iprint(f"  LR: {lr.to_string(elf)}")
        iprint(f"  PC: {pc.to_string(elf)}")

    # Stack contents
    iprint()
    iprint(bold("STACK CONTENTS AROUND SP:"))
    with indent():
        sp = thread.regs.gpr[13]
        for x in range(-16, stack_size):
            addr = 4 * x + sp
            data = core.read_vaddr(addr, 4)
            if data and len(data) == 4:
                val = u32(data, 0)
                prefix = "     "
                if addr == sp:
                    prefix = "SP =>"
                data_notation = core.get_address_notation(f"{prefix} 0x{addr:08x}", val)
                line = data_notation.to_string(elf)
                if addr == sp:
                    iprint(green(line))
                else:
                    iprint(line)


def _detect_input_type(filename):
    """Detect whether the input file is a crash log (.log) or core dump (.psp2dmp).
    Returns 'log' or 'coredump'.
    """
    ext = os.path.splitext(filename)[1].lower()
    if ext == ".log":
        return "log"
    if ext in (".psp2dmp", ".dmp"):
        return "coredump"

    # Heuristic: try reading as text to detect crash log format
    try:
        with open(filename, "r", errors="ignore") as f:
            header = f.read(512)
            if "CRASH:" in header and ("Hardware exception" in header or "Program crashed with signal" in header):
                return "log"
    except Exception:
        pass

    return "coredump"


def main_analyze_log(args):
    """Main entry point for crash log (.log) analysis mode."""

    # Print header
    iprint(bold("=" * 72))
    iprint(bold("  Godot Vita Crash Log Analyzer"))
    iprint(bold("=" * 72))
    iprint(f"  Log file:  {args.corefile}")
    iprint(f"  ELF file:  {args.elffile}")
    iprint(bold("=" * 72))
    iprint()

    # Parse crash log
    iprint(dim("Parsing crash log..."))
    log_data = parse_crash_log(args.corefile)

    # Parse ELF for symbol resolution
    elf = None
    iprint(dim("Parsing ELF file..."))
    elf = ElfParser(args.elffile, no_disasm=args.no_disasm)
    iprint()

    # Run analysis
    analyze_log(log_data, elf)

    # Disassembly around PC and LR if available
    if elf and not args.no_disasm and log_data.pc:
        # For EXEC ELF, the offset within the RX segment = addr - rx_vaddr
        if elf.rx_vaddr > 0:
            pc_offset = (log_data.pc & ~1) - elf.rx_vaddr
            if pc_offset > 0:
                iprint(bold(f"DISASSEMBLY AROUND PC (0x{log_data.pc & ~1:08x}):"))
                with indent():
                    elf.disas_around_addr(pc_offset)
                iprint()

            if log_data.lr:
                lr_offset = (log_data.lr & ~1) - elf.rx_vaddr
                if lr_offset > 0:
                    iprint(bold(f"DISASSEMBLY AROUND LR (0x{log_data.lr & ~1:08x}):"))
                    with indent():
                        elf.disas_around_addr(lr_offset)
                    iprint()

    # Cleanup
    if elf:
        elf.close()

    iprint(bold("=" * 72))
    iprint(bold("  Analysis complete."))
    iprint()
    iprint("  " + bold("Hint:") + " If symbols show '??' use arm-vita-eabi-addr2line manually:")
    iprint("    arm-vita-eabi-addr2line -e <elf> -f -C -p <address>")
    iprint()
    iprint("  " + bold("Hint:") + " Build with 'debug_symbols=yes' in SCons for better results.")
    iprint(bold("=" * 72))


def main_analyze_coredump(args):
    """Main entry point for core dump (.psp2dmp) analysis mode."""

    # Print header
    iprint(bold("=" * 72))
    iprint(bold("  Godot Vita Crash Dump Analyzer"))
    iprint(bold("=" * 72))
    iprint(f"  Core file: {args.corefile}")
    iprint(f"  ELF file:  {args.elffile}")
    iprint(bold("=" * 72))
    iprint()

    # Parse files
    iprint(dim("Parsing core dump..."))
    core = CoreParser(args.corefile)

    iprint(dim("Parsing ELF file..."))
    elf = ElfParser(args.elffile, no_disasm=args.no_disasm)

    # Show loaded modules if requested
    if args.show_modules:
        iprint()
        iprint(bold("=== LOADED MODULES ==="))
        with indent():
            for module in core.modules:
                print_module_info(module)
        iprint()

    # Show all threads
    iprint()
    iprint(bold("=== THREADS ==="))
    crashed = []
    with indent():
        for thread in core.threads:
            if thread.stop_reason != 0:
                crashed.append(thread)
            print_thread_info(core, thread, elf)
    iprint()

    # Detailed crash analysis for each crashed thread
    if not crashed:
        iprint(green("No crashed threads found in the core dump."))
    else:
        iprint(red(bold(f"Found {len(crashed)} crashed thread(s):")))
        iprint()
        for thread in crashed:
            analyze_crash(core, thread, elf, args.stacksize)
            iprint()

    # Cleanup
    elf.close()
    core.close()

    iprint(bold("=" * 72))
    iprint(bold("  Analysis complete."))
    if crashed:
        iprint()
        iprint("  " + bold("Hint:") + " If symbols show '??' use arm-vita-eabi-addr2line manually:")
        iprint("    arm-vita-eabi-addr2line -e <elf> -f -C -p <address>")
        iprint()
        iprint("  " + bold("Hint:") + " Build with 'debug_symbols=yes' in SCons for better results.")
    iprint(bold("=" * 72))


def main():
    parser = ArgumentParser(
        description="Godot Vita Crash Analyzer - Analyzes PSVita .psp2dmp core dumps and .log crash logs",
        epilog="Examples:\n"
               "  python analyze_crash.py crash.psp2dmp godot.vita.elf\n"
               "  python analyze_crash.py crash_20260413_005400.log godot.vita.elf\n",
    )
    parser.add_argument(
        "corefile",
        help="Path to the .psp2dmp core dump file or .log crash log file",
    )
    parser.add_argument(
        "elffile",
        help="Path to the .elf file (not .velf, not eboot.bin). Build with -g for best results.",
    )
    parser.add_argument(
        "-s",
        "--stack-size",
        dest="stacksize",
        type=int,
        default=32,
        metavar="N",
        help="Number of stack addresses to print after SP (default: 32)",
    )
    parser.add_argument(
        "--no-disasm",
        action="store_true",
        help="Skip disassembly output (useful if VitaSDK toolchain is not in PATH)",
    )
    parser.add_argument(
        "--no-color",
        action="store_true",
        help="Disable colored output",
    )
    parser.add_argument(
        "--show-modules",
        action="store_true",
        help="Show loaded modules information (core dump mode only)",
    )

    args = parser.parse_args()

    if args.no_color:
        set_color(False)

    # Validate input files
    if not os.path.isfile(args.corefile):
        print(red(f"ERROR: Input file not found: {args.corefile}"))
        sys.exit(1)
    if not os.path.isfile(args.elffile):
        print(red(f"ERROR: ELF file not found: {args.elffile}"))
        sys.exit(1)

    # Detect input type and dispatch
    input_type = _detect_input_type(args.corefile)

    if input_type == "log":
        main_analyze_log(args)
    else:
        main_analyze_coredump(args)


if __name__ == "__main__":
    main()
