class CoreParser:
    """Parses a PSVita core dump (.psp2dmp) file."""

    def __init__(self, filename):
        f = None
        # Detect gzip by magic bytes (\x1f\x8b) instead of relying on exceptions,
        # which is more reliable and avoids Python version differences.
        with open(filename, "rb") as probe:
            is_gzip = probe.read(2) == b"\x1f\x8b"
        if is_gzip:
            f = gzip.open(filename, "rb")
        else:
            f = open(filename, "rb")
        self.elf = ELFFile(f)

        self._file = f
        self.notes = {}
        self.segments = []
        self.modules = []
        self.threads = []
        self.tid_to_thread = {}

        self._init_notes()
        self._parse_modules()
        self._parse_threads()
        self._parse_thread_regs()

    def close(self):
        if self._file:
            self._file.close()

    def _init_notes(self):
        for seg in self.elf.iter_segments():
            if seg.header.p_type == "PT_NOTE":
                for note in seg.iter_notes():
                    self.notes[note["n_name"]] = note["n_desc"]
            elif seg.header.p_type == "PT_LOAD":
                self.segments.append(Segment(seg.header.p_vaddr, seg.data()))

    def _parse_modules(self):
        data = self.notes.get("MODULE_INFO")
        if not data:
            return

        num = u32(data, 4)
        off = 8
        for _ in range(num):
            # Module header
            sz = 0x50
            module = VitaModule(data[off : off + sz])
            off += sz
            # Module segments
            sz = module.num_segs * 0x14
            module.parse_segs(data[off : off + sz])
            off += sz
            # Module footer
            sz = 0x10
            module.parse_foot(data[off : off + sz])
            off += sz

            self.modules.append(module)

    def _parse_threads(self):
        data = self.notes.get("THREAD_INFO")
        if not data:
            return

        num = u32(data, 4)
        off = 8
        for _ in range(num):
            sz = u32(data, off)
            thread = VitaThread(data[off : off + sz])
            self.threads.append(thread)
            self.tid_to_thread[thread.uid] = thread
            off += sz

    def _parse_thread_regs(self):
        data = self.notes.get("THREAD_REG_INFO")
        if not data:
            return

        num = u32(data, 4)
        off = 8
        for _ in range(num):
            sz = u32(data, off)
            regs = VitaRegs(data[off : off + sz])
            if regs.tid in self.tid_to_thread:
                self.tid_to_thread[regs.tid].regs = regs
            off += sz

    def _build_rx_ranges(self):
        """Build a sorted list of executable (RX) memory ranges from all modules."""
        self._rx_ranges = []
        for module in self.modules:
            for segment in module.segments:
                if (segment.attr & 0xF) == 5:  # RX
                    self._rx_ranges.append((segment.start, segment.start + segment.size, module, segment))
        self._rx_ranges.sort(key=lambda r: r[0])

    def is_code_address(self, addr):
        """Check if an address falls within any executable (RX) segment.
        Returns (module, segment, offset) tuple or None.
        Thumb bit is cleared before lookup to handle Thumb function pointers.
        """
        if not hasattr(self, "_rx_ranges"):
            self._build_rx_ranges()
        addr_clean = addr & ~1
        for start, end, module, segment in self._rx_ranges:
            if start <= addr_clean < end:
                return (module, segment, addr_clean - start)
        return None

    def get_address_notation(self, symbol, vaddr):
        """Resolve a virtual address to a module/segment/offset notation."""
        for module in self.modules:
            for segment in module.segments:
                if segment.start <= vaddr < segment.start + segment.size:
                    return VitaAddress(symbol, vaddr, module, segment, vaddr - segment.start)
        return VitaAddress(symbol, vaddr)

    def read_vaddr(self, addr, size):
        """Read bytes from a virtual address in the core dump."""
        for segment in self.segments:
            if segment.vaddr <= addr < segment.vaddr + segment.size:
                off = addr - segment.vaddr
                return segment.data[off : off + size]
        return None


