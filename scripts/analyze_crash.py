#!/usr/bin/env python3
"""
Godot Vita Crash Dump Analyzer
===============================
Analyzes PSVita crash dump files (.psp2dmp) generated by the Vita kernel
when a homebrew application crashes.

Based on vita-parse-core (https://github.com/xyzz/vita-parse-core)
Rewritten for Python 3 compatibility and customized for the Godot Vita project.

Requirements:
    pip install pyelftools

Usage:
    python analyze_crash.py <core_file.psp2dmp> <elf_file.elf> [options]

    Options:
        -s, --stack-size    Number of stack addresses to print (default: 32)
        --no-disasm         Skip disassembly output (if toolchain not available)
        --no-color          Disable colored output

Example:
    python analyze_crash.py ux0_data_crash.psp2dmp godot.vita.elf
"""

