class VitaThread:
    """Represents a thread from the core dump."""

    def __init__(self, data):
        self.uid = u32(data, 4)
        self.name = c_str(data, 8)
        self.stop_reason = u32(data, 0x74)
        self.status = u16(data, 0x30)
        self.pc = u32(data, 0x9C)
        self.regs = None  # Assigned later

    def __str__(self):
        return f"{self.name} <0x{self.uid:x}>"


class VitaModuleSegment:
    """Represents a segment within a loaded module."""

    def __init__(self, data, num):
        self.num = num
        self.attr = u32(data, 4)
        self.start = u32(data, 8)
        self.size = u32(data, 12)
        self.align = u32(data, 16)


class VitaModule:
    """Represents a loaded module from the core dump."""

    def __init__(self, data):
        self.uid = u32(data, 4)
        self.num_segs = u32(data, 0x4C)
        self.name = c_str(data, 0x24)
        self.segments = []

    def parse_segs(self, data):
        self.segments = []
        for x in range(self.num_segs):
            sz = 0x14
            self.segments.append(VitaModuleSegment(data[sz * x : sz * (x + 1)], x + 1))

    def parse_foot(self, data):
        # ARM exception start/end (unused for now)
        pass


class VitaRegs:
    """Represents the register state of a thread."""

    def __init__(self, data):
        self.tid = u32(data, 4)
        self.gpr = []
        for x in range(16):
            self.gpr.append(u32(data, 8 + 4 * x))


class VitaAddress:
    """Represents a resolved virtual address with optional module/segment info."""

    def __init__(self, symbol, vaddr, module=None, segment=None, offset=None):
        self._symbol = symbol
        self._module = module
        self._segment = segment
        self._offset = offset
        self._vaddr = vaddr

    def is_located(self):
        return self._module and self._segment and self._offset is not None

    def print_disas_if_available(self, elf):
        if not elf or not self.is_located():
            return

        addr_to_display = self._vaddr
        if addr_to_display & 1 == 0:
            state = "ARM"
        else:
            state = "Thumb"
            addr_to_display &= ~1

        iprint()
        iprint(bold(f"DISASSEMBLY AROUND {self._symbol}: 0x{addr_to_display:x} ({state}):"))
        elf.disas_around_addr(self._offset)

    def to_string(self, elf=None):
        if self.is_located():
            output = f"{self._symbol}: 0x{self._vaddr:x} ({self._module.name}@{self._segment.num} + 0x{self._offset:x}"
            if elf and self._module.name.endswith(".elf") and self._segment.num == 1:
                a2l_result = elf.addr2line(self._offset)
                if a2l_result:
                    output += f" => {a2l_result}"
            output += ")"
        else:
            output = f"{self._symbol}: 0x{self._vaddr:x}"
        return output

    def __str__(self):
        return self.to_string()


class Segment:
    """Represents a memory segment from the core dump."""

    def __init__(self, vaddr, data):
        self.vaddr = vaddr
        self.data = data
        self.size = len(data)


