STR_STOP_REASON = defaultdict(
    lambda: "Unknown",
    {
        0x00000: "No reason",
        0x30002: "Undefined instruction exception",
        0x30003: "Prefetch abort exception",
        0x30004: "Data abort exception",
        0x60080: "Division by zero",
    },
)

STR_STATUS = defaultdict(
    lambda: "Unknown",
    {
        1: "Running",
        8: "Waiting",
        16: "Not started",
    },
)

STR_ATTR = defaultdict(
    lambda: "??",
    {
        5: "RX",
        6: "RW",
    },
)

REG_NAMES = {
    13: "SP",
    14: "LR",
    15: "PC",
}


