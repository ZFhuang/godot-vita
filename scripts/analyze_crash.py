class CrashLogData:
    """Parsed data from a crash log file generated by crash_handler_vita.cpp."""

    def __init__(self):
        self.crash_type = ""           # e.g. "Hardware exception - Data Abort"
        self.engine_version = ""
        self.process_uptime = ""
        self.thread_name = ""
        self.thread_id = 0
        self.thread_priority = 0
        self.thread_cpu = 0
        self.stack_size = 0
        self.stack_free = 0
        self.mem_user = 0
        self.mem_cdram = 0
        self.mem_phycont = 0
        self.regs = {}                 # register name -> int value
        self.pc = 0
        self.lr = 0
        self.sp = 0
        self.spsr = 0
        self.fsr = 0
        self.far = 0
        self.fault_type = ""           # decoded FSR string
        self.backtrace_addrs = []      # list of (label, addr) tuples
        self.stack_scan_addrs = []     # list of (label, addr) tuples from stack scanning
        self.is_signal_crash = False   # True if signal-based, False if hw exception
        self.signal_num = 0
        self.signal_name = ""


def parse_crash_log(filename):
    """Parse a crash log file (.log) generated by crash_handler_vita.cpp.

    Returns a CrashLogData object with all extracted fields.
    """
    data = CrashLogData()

    with open(filename, "r") as f:
        lines = f.readlines()

    for line in lines:
        line = line.strip()

        # Crash type header
        m = re.match(r"CRASH:\s*Hardware exception\s*-\s*(.+)", line)
        if m:
            data.crash_type = f"Hardware exception - {m.group(1)}"
            data.is_signal_crash = False
            continue

        m = re.match(r"CRASH:\s*Program crashed with signal\s+(\d+)\s*-\s*(.+)", line)
        if m:
            data.signal_num = int(m.group(1))
            data.signal_name = m.group(2)
            data.crash_type = f"Signal {data.signal_num} - {data.signal_name}"
            data.is_signal_crash = True
            continue

        # Engine version
        m = re.match(r"Engine version:\s*(.+)", line)
        if m:
            data.engine_version = m.group(1)
            continue

        # Process uptime
        m = re.match(r"Process uptime:\s*(.+)", line)
        if m:
            data.process_uptime = m.group(1)
            continue

        # Thread info
        m = re.match(r"Name:\s*(\S+)\s+TID:\s*(0x[0-9a-fA-F]+)\s+Priority:\s*(\d+)\s+CPU:\s*(\d+)", line)
        if m:
            data.thread_name = m.group(1)
            data.thread_id = int(m.group(2), 16)
            data.thread_priority = int(m.group(3))
            data.thread_cpu = int(m.group(4))
            continue

        m = re.match(r"Stack size:\s*(\d+)", line)
        if m:
            data.stack_size = int(m.group(1))
            continue

        m = re.match(r"Stack free:\s*(\d+)", line)
        if m:
            data.stack_free = int(m.group(1))
            continue

        # Memory info
        m = re.match(r"User RAM free:\s*(\d+)", line)
        if m:
            data.mem_user = int(m.group(1))
            continue

        m = re.match(r"CDRAM free:\s*(\d+)", line)
        if m:
            data.mem_cdram = int(m.group(1))
            continue

        m = re.match(r"Phycont free:\s*(\d+)", line)
        if m:
            data.mem_phycont = int(m.group(1))
            continue

        # Registers (multiple formats from the log)
        # Format: R0=0x... R1=0x... etc. on one line
        reg_matches = re.findall(r"(R\d+|SP|LR|PC|SPSR|FSR|FAR)=(0x[0-9a-fA-F]+)", line)
        if reg_matches:
            for name, val_str in reg_matches:
                val = int(val_str, 16)
                data.regs[name] = val
                if name == "PC":
                    data.pc = val
                elif name == "LR":
                    data.lr = val
                elif name == "SP":
                    data.sp = val
                elif name == "SPSR":
                    data.spsr = val
                elif name == "FSR":
                    data.fsr = val
                elif name == "FAR":
                    data.far = val
            continue

        # Fault type
        m = re.match(r"Fault type:\s*(.+)", line)
        if m:
            data.fault_type = m.group(1)
            continue

        # Backtrace entries: [PC] 0x..., [LR] 0x..., [ 2] 0x..., [0] [0x...]
        m = re.match(r"\[(PC|LR|\s*\d+)\]\s*(?:\[?)?(0x[0-9a-fA-F]+)", line)
        if m:
            label = m.group(1).strip()
            addr = int(m.group(2), 16)
            data.backtrace_addrs.append((label, addr))
            continue

        # Stack scan entries: [S 0] 0x..., [S 1] 0x..., etc.
        m = re.match(r"\[S\s*(\d+)\]\s*(0x[0-9a-fA-F]+)", line)
        if m:
            label = f"S{m.group(1)}"
            addr = int(m.group(2), 16)
            data.stack_scan_addrs.append((label, addr))
            continue

    return data


def _decode_fsr_python(fsr):
    """Decode ARM FSR (Fault Status Register) to human-readable string.
    Mirrors the C implementation in crash_handler_vita.cpp."""
    fs = ((fsr >> 10) & 0x1) << 4 | (fsr & 0xF)
    fsr_table = {
        0x01: "Alignment fault",
        0x02: "Debug event",
        0x03: "Access flag fault (Section)",
        0x04: "Instruction cache maintenance fault",
        0x05: "Translation fault (Section)",
        0x06: "Access flag fault (Page)",
        0x07: "Translation fault (Page)",
        0x08: "Synchronous external abort (non-translation)",
        0x09: "Domain fault (Section)",
        0x0B: "Domain fault (Page)",
        0x0C: "Synchronous external abort on translation (1st level)",
        0x0D: "Permission fault (Section)",
        0x0E: "Synchronous external abort on translation (2nd level)",
        0x0F: "Permission fault (Page)",
        0x10: "TLB conflict abort",
        0x16: "Asynchronous external abort",
        0x19: "Synchronous parity error on memory access",
        0x1C: "Synchronous parity error on translation (1st level)",
        0x1E: "Synchronous parity error on translation (2nd level)",
    }
    return fsr_table.get(fs, f"Unknown fault type (FS=0x{fs:02x})")


def _analyze_fault_cause(data):
    """Heuristic analysis of the crash cause based on FAR, FSR, and registers."""
    causes = []

    far = data.far
    fsr = data.fsr

    # NULL pointer dereference: FAR is a small offset from 0
    if far < 0x1000:
        if far == 0:
            causes.append(f"NULL pointer dereference (FAR=0x{far:08x}, direct NULL access)")
        else:
            causes.append(
                f"NULL pointer dereference (FAR=0x{far:08x}, "
                f"accessing member at offset 0x{far:x} of a NULL object)"
            )

    # Stack overflow check: FAR near SP
    elif data.sp != 0 and abs(far - data.sp) < 0x1000:
        causes.append(f"Possible stack overflow (FAR=0x{far:08x} near SP=0x{data.sp:08x})")

    # Use-after-free / wild pointer: FAR in valid range but unmapped
    elif 0x81000000 <= far <= 0xBFFFFFFF:
        causes.append(
            f"Invalid memory access at 0x{far:08x} "
            f"(possible use-after-free or dangling pointer)"
        )
    else:
        causes.append(f"Invalid memory access at FAR=0x{far:08x}")

    # Check for NULL registers that might indicate the source
    null_regs = [name for name in ["R0", "R1", "R2", "R3"] if data.regs.get(name, -1) == 0]
    if null_regs:
        causes.append(f"Registers with NULL value: {', '.join(null_regs)}")

    # Memory warnings
    if data.mem_user > 0 and data.mem_user < 1024 * 1024:
        causes.append(f"WARNING: User RAM critically low ({data.mem_user} bytes free)")

    return causes


def analyze_log(log_data, elf):
    """Perform detailed analysis of a parsed crash log."""

    # Header
    iprint(red(bold("=" * 72)))
    iprint(red(bold(f"  CRASH: {log_data.crash_type}")))
    iprint(red(bold("=" * 72)))
    iprint()

    # Basic info
    iprint(bold("CRASH INFO:"))
    with indent():
        iprint(f"Type:    {log_data.crash_type}")
        if log_data.engine_version:
            iprint(f"Engine:  {log_data.engine_version}")
        if log_data.process_uptime:
            iprint(f"Uptime:  {log_data.process_uptime}")
        if log_data.fault_type:
            iprint(f"Fault:   {red(log_data.fault_type)}")
        if log_data.far != 0 or log_data.fsr != 0:
            iprint(f"FAR:     0x{log_data.far:08x}")
            iprint(f"FSR:     0x{log_data.fsr:08x} ({_decode_fsr_python(log_data.fsr)})")
    iprint()

    # Thread info
    if log_data.thread_name:
        iprint(bold("THREAD INFO:"))
        with indent():
            iprint(f"Name:     {cyan(log_data.thread_name)}")
            iprint(f"TID:      0x{log_data.thread_id:08x}")
            iprint(f"Priority: {log_data.thread_priority}")
            iprint(f"CPU:      {log_data.thread_cpu}")
            if log_data.stack_size > 0:
                iprint(f"Stack:    {log_data.stack_size} bytes (free: {log_data.stack_free} bytes)")
        iprint()

    # Memory info
    if log_data.mem_user > 0 or log_data.mem_cdram > 0:
        iprint(bold("MEMORY INFO:"))
        with indent():
            if log_data.mem_user > 0:
                mb = log_data.mem_user / (1024 * 1024)
                iprint(f"User RAM free:  {log_data.mem_user:>12} bytes ({mb:.2f} MB)")
            if log_data.mem_cdram > 0:
                mb = log_data.mem_cdram / (1024 * 1024)
                iprint(f"CDRAM free:     {log_data.mem_cdram:>12} bytes ({mb:.2f} MB)")
            if log_data.mem_phycont > 0:
                mb = log_data.mem_phycont / (1024 * 1024)
                iprint(f"Phycont free:   {log_data.mem_phycont:>12} bytes ({mb:.2f} MB)")
        iprint()

    # Registers
    iprint(bold("REGISTERS:"))
    with indent():
        # Print R0-R12 in rows of 4
        for row_start in range(0, 13, 4):
            parts = []
            for i in range(row_start, min(row_start + 4, 13)):
                name = f"R{i}"
                val = log_data.regs.get(name, None)
                if val is not None:
                    val_str = f"0x{val:08x}"
                    if val == 0:
                        val_str = red(val_str)
                    parts.append(f"{name:>3}={val_str}")
            if parts:
                iprint("  ".join(parts))
        # SP, LR, PC
        iprint(f" SP=0x{log_data.sp:08x}  LR=0x{log_data.lr:08x}  PC=0x{log_data.pc:08x}")
        if log_data.spsr:
            iprint(f"SPSR=0x{log_data.spsr:08x}")
    iprint()

    # Resolve addresses with addr2line
    iprint(bold("BACKTRACE (with symbol resolution):"))
    with indent():
        # Collect all addresses to resolve
        all_addrs = []
        for label, addr in log_data.backtrace_addrs:
            all_addrs.append((label, addr))

        if not all_addrs:
            # Fall back to PC/LR if no backtrace section
            if log_data.pc:
                all_addrs.append(("PC", log_data.pc))
            if log_data.lr:
                all_addrs.append(("LR", log_data.lr))

        if not all_addrs:
            iprint(yellow("  (no addresses to resolve)"))
        else:
            for idx, (label, addr) in enumerate(all_addrs):
                addr_clean = addr & ~1  # Clear Thumb bit
                sym_str = ""
                if elf:
                    # For EXEC-type ELF, addresses are absolute.
                    # addr2line expects the absolute address directly.
                    a2l_result = elf.addr2line_absolute(addr_clean)
                    if a2l_result:
                        sym_str = f" => {a2l_result}"

                frame_str = f"#{idx:<3} [{label:>2}] 0x{addr_clean:08x}{sym_str}"
                if label in ("PC", "LR"):
                    iprint(cyan(frame_str))
                else:
                    iprint(frame_str)

        # Also try to resolve PC/LR even if they appear in backtrace,
        # to give a clear summary
        iprint()
        iprint(bold("KEY ADDRESSES:"))
        with indent():
            for name, addr in [("PC", log_data.pc), ("LR", log_data.lr)]:
                if addr == 0:
                    continue
                addr_clean = addr & ~1
                sym_str = ""
                if elf:
                    a2l_result = elf.addr2line_absolute(addr_clean)
                    if a2l_result:
                        sym_str = f" => {a2l_result}"
                iprint(f"{name}: 0x{addr_clean:08x}{sym_str}")
    iprint()

    # Stack scan results (heuristic candidates)
    if log_data.stack_scan_addrs:
        iprint(bold("STACK SCAN (heuristic candidates, may contain false positives):"))
        iprint(dim("  These are values found on the stack that point into executable code."))
        iprint(dim("  They are likely return addresses from the call chain, but may include"))
        iprint(dim("  function pointers, vtable entries, or other code references."))
        iprint()
        with indent():
            for idx, (label, addr) in enumerate(log_data.stack_scan_addrs):
                addr_clean = addr & ~1
                sym_str = ""
                if elf:
                    a2l_result = elf.addr2line_absolute(addr_clean)
                    if a2l_result:
                        sym_str = f" => {a2l_result}"
                frame_str = f"#{idx:<3} ? 0x{addr_clean:08x}{sym_str}"
                iprint(dim(frame_str))
        iprint()

    # Heuristic cause analysis
    if not log_data.is_signal_crash:
        causes = _analyze_fault_cause(log_data)
        if causes:
            iprint(bold("PROBABLE CAUSE:"))
            with indent():
                for cause in causes:
                    iprint(red(f"• {cause}"))
            iprint()


