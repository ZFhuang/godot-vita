class ElfParser:
    """Parses the homebrew ELF file for symbol resolution and disassembly."""

    def __init__(self, filename, no_disasm=False):
        self.filename = filename
        self.no_disasm = no_disasm
        self.rx_vaddr = -1
        self.a2l = None
        self._a2l_cache = {}
        self._a2l_abs_cache = {}

        with open(filename, "rb") as f:
            elf = ELFFile(f)
            for seg in elf.iter_segments():
                if seg["p_type"] == "PT_LOAD" and seg["p_flags"] == 5:
                    self.rx_vaddr = seg["p_vaddr"]

        # Always try to open addr2line for symbol resolution.
        # --no-disasm only skips objdump disassembly output.
        self._open_addr2line()

    def _open_addr2line(self):
        """Open a persistent addr2line subprocess for symbol resolution."""
        addr2line_bin = shutil.which("arm-vita-eabi-addr2line")
        if not addr2line_bin:
            iprint(yellow("WARNING: arm-vita-eabi-addr2line not found in PATH. Symbol resolution disabled."))
            self.a2l = None
            return

        try:
            self.a2l = subprocess.Popen(
                ["arm-vita-eabi-addr2line", "-e", self.filename, "-f", "-p", "-C"],
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            )
        except FileNotFoundError:
            self.a2l = None

    def addr2line(self, addr):
        """Resolve an offset in the executable segment to a source location.
        Results are cached to avoid redundant subprocess calls for the same address.
        """
        if not self.a2l:
            return None
        if addr in self._a2l_cache:
            return self._a2l_cache[addr]
        real_addr = addr + self.rx_vaddr
        try:
            self.a2l.stdin.write(f"{hex(real_addr)}\n".encode())
            self.a2l.stdin.flush()
            out = self.a2l.stdout.readline()
            result = out.decode().strip() or None
        except (BrokenPipeError, OSError):
            result = None
        self._a2l_cache[addr] = result
        return result

    def addr2line_absolute(self, addr):
        """Resolve an absolute virtual address to a source location.
        For EXEC-type ELF files where runtime addresses match ELF addresses.
        Results are cached.
        """
        if not self.a2l:
            return None
        if addr in self._a2l_abs_cache:
            return self._a2l_abs_cache[addr]
        try:
            self.a2l.stdin.write(f"{hex(addr)}\n".encode())
            self.a2l.stdin.flush()
            out = self.a2l.stdout.readline()
            result = out.decode().strip() or None
            # Filter out unhelpful results like "?? ??:0"
            if result and "??" in result and ":0" in result:
                result = None
        except (BrokenPipeError, OSError):
            result = None
        self._a2l_abs_cache[addr] = result
        return result

    def disas_around_addr(self, addr):
        """Disassemble code around the given offset in the executable segment."""
        if self.no_disasm:
            iprint(dim("  (disassembly skipped, --no-disasm flag set)"))
            return

        objdump_bin = shutil.which("arm-vita-eabi-objdump")
        if not objdump_bin:
            iprint(yellow("  (arm-vita-eabi-objdump not found, skipping disassembly)"))
            return

        if addr & 1 != 0:
            addr &= ~1
            thumb = True
        else:
            thumb = False

        real_addr = addr + self.rx_vaddr
        start = real_addr - 0x10
        end = real_addr + 0x10

        args = [
            "arm-vita-eabi-objdump",
            "-d",
            "-S",
            f"--start-address=0x{start:x}",
            f"--stop-address=0x{end:x}",
            self.filename,
        ]
        if thumb:
            args.append("-Mforce-thumb")

        try:
            output = subprocess.check_output(args, stderr=subprocess.DEVNULL)
            lines = output.decode(errors="replace").split("\n")

            # Filter to only show disassembly section content
            keep = False
            filtered = []
            for line in lines:
                if "Disassembly of section" in line:
                    keep = True
                    continue
                if keep:
                    filtered.append(line)

            for line in filtered:
                if f"{real_addr:x}:" in line:
                    # Highlight the crash address
                    tab_idx = line.find("\t")
                    if tab_idx >= 0:
                        line = f"!!! \t{line[tab_idx:]} !!!"
                    iprint(red(line))
                else:
                    iprint(dim(line))
        except (subprocess.CalledProcessError, FileNotFoundError) as e:
            iprint(yellow(f"  (disassembly failed: {e})"))

    def close(self):
        if self.a2l:
            try:
                self.a2l.kill()
            except OSError:
                pass


